#!/usr/bin/env python3
"""Generate the placeholder mapping JSON from the Java entity definitions.

Scans every .java file under the given roots for

    EntityDefinition.define(NAME, eb -> { eb.physicalTable("t"); eb.field("f", f -> f.physicalColumn("c")...) })

and writes {"Entity": "table", "Entity.field": "column", ...} to stdout.

Temporal entities (`eb.temporal(...)`) are written as objects instead of a table name:
  "Entity": {"table": "t", "pk": "col", "writeOnce": false,
             "columns": {"versionNo": "version_no", "effectStartTime": "...", "createdTime": "...", "deleted": "..."}}
The system column defaults come from TemporalSpec.java; `t.column("field", "col")` overrides them.

Limits (reported on stderr, not silently skipped):
  * fields generated by helper methods (column names in variables) are matched by name only;

Usage:
  python3 tools/gen_mapping.py <repo>/backend [more roots...] > mapping.json
"""

import json
import re
import sys
from pathlib import Path

CONST_RE = re.compile(r'static\s+final\s+String\s+(\w+)\s*=\s*"([^"]+)"\s*;')
DEFINE_RE = re.compile(r"EntityDefinition\.define\(\s*([\w.\"]+)\s*,")
TABLE_RE = re.compile(r'eb\.physicalTable\(\s*"([^"]+)"\s*\)')
FIELD_RE = re.compile(
    r'eb\.field\(\s*("([^"]+)"|(\w+))\s*,\s*f\s*->\s*f\.physicalColumn\(\s*"([^"]+)"\s*\)'
)
TEMPORAL_RE = re.compile(r"eb\.temporal\(")
PRIMARY_RE = re.compile(r'eb\.primaryKey\(\s*"(\w+)"\s*\)')
TEMPORAL_COLUMN_RE = re.compile(r'\.column\(\s*"(\w+)"\s*,\s*"(\w+)"\s*\)')
# helper(eb, "field", "column") with two string literals
HELPER_RE = re.compile(r'\b(\w+)\(\s*eb\s*,\s*"(\w+)"\s*,\s*"(\w+)"\s*\)')


def java_files(roots):
    """Main sources only: test code reuses the same constant names with other values."""
    for root in roots:
        for path in Path(root).rglob("*.java"):
            if "src/test" not in path.as_posix():
                yield path


def collect_constants(files):
    """Returns (per_file, global_unique). Many classes reuse names such as CARD with other values."""
    per_file, seen = {}, {}
    for path in files:
        text = path.read_text(encoding="utf-8", errors="ignore")
        local = {name: value for name, value in CONST_RE.findall(text)}
        per_file[path] = local
        for name, value in local.items():
            seen.setdefault(name, set()).add(value)
    unique = {name: next(iter(vals)) for name, vals in seen.items() if len(vals) == 1}
    return per_file, unique


def block_after(text, start):
    """Return the text of the lambda body starting at the first '{' after start."""
    brace = text.index("{", start)
    depth = 0
    for i in range(brace, len(text)):
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[brace : i + 1]
    return text[brace:]


def call_args(text, open_paren):
    """Text between the parenthesis at open_paren and its matching close parenthesis."""
    depth = 0
    for i in range(open_paren, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return text[open_paren + 1 : i]
    return text[open_paren + 1 :]


def temporal_defaults(files):
    """System column defaults (logical name -> physical column), read from TemporalSpec.java."""
    for path in files:
        if path.name == "TemporalSpec.java":
            text = path.read_text(encoding="utf-8", errors="ignore")
            consts = dict(CONST_RE.findall(text))
            block = re.search(r"DEFAULT_COLUMNS\s*=\s*Map\.of\((.*?)\);", text, re.S)
            if block:
                pairs = re.findall(r"(\w+)\s*,\s*\"(\w+)\"", block.group(1))
                return {consts.get(name, name): physical for name, physical in pairs}
    return {}


def temporal_spec(body, entity, columns, defaults):
    """Object for a temporal entity: table, primary key column, write-once flag and system columns."""
    t = TEMPORAL_RE.search(body)
    args = call_args(body, body.index("(", t.start())) if t else ""
    system = dict(defaults)
    for logical, physical in TEMPORAL_COLUMN_RE.findall(args):
        system[logical] = physical
    pk = PRIMARY_RE.search(body)
    pk_column = columns.get(f"{entity}.{pk.group(1)}") if pk else None
    return {
        "pk": pk_column,
        "writeOnce": "writeOnce()" in args,
        "columns": system,
    }


def resolve(token, path, per_file, unique):
    token = token.strip()
    if token.startswith('"'):
        return token.strip('"')
    name = token.split(".")[-1]
    return per_file.get(path, {}).get(name) or unique.get(name) or token


def main(roots):
    files = list(java_files(roots))
    per_file, unique = collect_constants(files)
    tables, columns, temporal, unresolved = {}, {}, {}, []
    defaults = temporal_defaults(files)

    # Shared publisher fields: PublisherKind.declare(eb, ...) writes publisherKind/publisherId.
    publisher_path = next((p for p in files if p.name == "PublisherKind.java"), None)
    publisher_consts = per_file.get(publisher_path, {}) if publisher_path else {}

    for path in files:
        text = path.read_text(encoding="utf-8", errors="ignore")
        for m in DEFINE_RE.finditer(text):
            entity = resolve(m.group(1), path, per_file, unique)
            body = block_after(text, m.end())
            table = TABLE_RE.search(body)
            if table:
                tables.setdefault(entity, table.group(1))
            for f in FIELD_RE.finditer(body):
                field = f.group(2) or resolve(f.group(3), path, per_file, unique)
                columns.setdefault(f"{entity}.{field}", f.group(4))
            # Helper calls like count(eb, "views", "views") declare field -> column.
            for h in HELPER_RE.finditer(body):
                columns.setdefault(f"{entity}.{h.group(2)}", h.group(3))
            if "PublisherKind.declare" in body and publisher_consts:
                columns.setdefault(f"{entity}.publisherKind", "publisher_kind")
                id_col = publisher_consts.get("ID_COLUMN")
                if id_col:
                    columns.setdefault(f"{entity}.publisherId", id_col)
            if TEMPORAL_RE.search(body):
                temporal[entity] = body
            if not table:
                unresolved.append(entity)

    mapping = {}
    mapping.update(tables)
    mapping.update(columns)
    missing_pk = []
    for entity, body in temporal.items():
        if entity not in tables:
            continue
        spec = temporal_spec(body, entity, columns, defaults)
        spec["table"] = tables[entity]
        if not spec["pk"]:
            missing_pk.append(entity)
        mapping[entity] = spec
    json.dump(dict(sorted(mapping.items())), sys.stdout, indent=2, ensure_ascii=False)
    print()

    if temporal:
        print("temporal (read as latest version at asOf): " + ", ".join(sorted(temporal)), file=sys.stderr)
    if missing_pk:
        print("temporal entities without a resolved primary key column: " + ", ".join(sorted(missing_pk)), file=sys.stderr)
    print("NOTE: helper-generated fields are matched by name only; check them against the Java source.", file=sys.stderr)
    if unresolved:
        print("entities without physicalTable: " + ", ".join(sorted(set(unresolved))), file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
